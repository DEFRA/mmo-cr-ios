require "minitest/autorun"
require "json"
require "open3"
require "plist"
require "tmpdir"
require "xcodeproj"
require_relative "../lib/cr_release"

# The app configuration standard (ADR-0020): the schema is the only maintained file; Xcode generates Info.plist,
# a Debug-only build phase adds MMOCRAppConfig locally, and the release pipeline writes it for every release.
class ProjectConfigTest < Minitest::Test
  ROOT = File.expand_path("../..", __dir__)
  APP_TARGET = "record-catch".freeze
  SCRIPT = "scripts/inject-app-config.sh".freeze
  PLUTIL = "/usr/bin/plutil".freeze
  IDENTITY_XCCONFIGS = %w[Base.xcconfig Dev.xcconfig Test.xcconfig Prod.xcconfig].freeze
  LOCALHOST_ONLY_ATS = { "NSExceptionDomains" => { "localhost" => { "NSExceptionAllowsInsecureHTTPLoads" => true } } }.freeze

  def app_target
    @app_target ||= Xcodeproj::Project.open(File.join(ROOT, "record-catch.xcodeproj"))
                                      .targets.find { |target| target.name == APP_TARGET }
  end

  def schema_keys
    CrRelease::AppConfig.load_schema.keys
  end

  def read_plist(path)
    xml, status = Open3.capture2(PLUTIL, "-convert", "xml1", "-o", "-", path)
    assert status.success?, "cannot read #{path}"
    Plist.parse_xml(xml)
  end

  def run_script(plist, configuration:, action: "build", env: {})
    env = { "CONFIGURATION" => configuration, "ACTION" => action, "SRCROOT" => ROOT,
            "TARGET_BUILD_DIR" => File.dirname(plist), "INFOPLIST_PATH" => File.basename(plist) }.merge(env)
    Open3.capture3(env, File.join(ROOT, SCRIPT))
  end

  def test_no_info_plist_is_committed
    tracked = `git -C #{ROOT} ls-files`.lines.map(&:chomp)
    assert_empty tracked.grep(%r{(\A|/)Info[^/]*\.plist\z}), "Info.plist is generated by Xcode; do not commit one"
  end

  def test_app_configurations_generate_info_plist_from_base_xcconfig
    app_target.build_configurations.each do |config|
      settings = config.build_settings
      assert_equal "Base.xcconfig", config.base_configuration_reference&.path, config.name
      assert_equal "YES", settings["GENERATE_INFOPLIST_FILE"], config.name
      assert_nil settings["INFOPLIST_FILE"], "#{config.name}: no Info.plist template; the build phase adds config"
      assert_equal config.name.start_with?("Debug"), settings.key?("INFOPLIST_KEY_NSLocalNetworkUsageDescription"),
                   "#{config.name}: the local-network prompt is for Debug builds only"
    end
  end

  def test_inject_app_config_is_the_last_build_phase_and_runs_every_build
    phase = app_target.build_phases.last
    assert_kind_of Xcodeproj::Project::Object::PBXShellScriptBuildPhase, phase
    assert_includes phase.shell_script, SCRIPT
    assert_equal "1", phase.always_out_of_date
    assert_includes phase.input_paths, "$(TARGET_BUILD_DIR)/$(INFOPLIST_PATH)"
    assert_includes phase.input_paths, "$(SRCROOT)/Config/app-config.schema.json"
    assert File.executable?(File.join(ROOT, SCRIPT)), "#{SCRIPT} must be executable"
  end

  def test_committed_xcconfigs_are_identity_files_without_stage_values
    Dir.glob(File.join(ROOT, "Config", "*.xcconfig")).reject { |path| path.end_with?("/Local.xcconfig") }.each do |path|
      assert_includes IDENTITY_XCCONFIGS, File.basename(path)
      refute_match(/^\s*(#{CrRelease::AppConfig::PREFIX}|API_BASE_URL)/, File.read(path), "#{path} sets a stage value")
    end
  end

  def test_local_xcconfig_is_git_ignored
    assert system("git", "-C", ROOT, "check-ignore", "-q", "Config/Local.xcconfig"), "Config/Local.xcconfig must be ignored"
  end

  def test_script_leaves_release_builds_and_archives_untouched
    Dir.mktmpdir do |dir|
      plist = File.join(dir, "Info.plist")
      File.write(plist, "untouched")
      [["Release", "build"], ["Debug", "install"]].each do |configuration, action|
        _out, err, status = run_script(plist, configuration: configuration, action: action)
        assert status.success?, err
        assert_equal "untouched", File.read(plist), "#{configuration}/#{action} must be left to the release pipeline"
      end
    end
  end

  def test_script_writes_every_schema_key_and_localhost_ats_in_debug
    skip "needs macOS plutil" unless File.executable?(PLUTIL)
    Dir.mktmpdir do |dir|
      plist = File.join(dir, "Info.plist")
      system(PLUTIL, "-create", "binary1", plist, exception: true)
      _out, err, status = run_script(plist, configuration: "Debug",
                                            env: { "CR_APP_CFG_API_BASE_URL" => "http://localhost:3002" })
      assert status.success?, err

      written = read_plist(plist)
      assert_equal schema_keys.sort, written.fetch(CrRelease::AppConfig::PLIST_KEY).keys.sort
      assert_equal "http://localhost:3002", written[CrRelease::AppConfig::PLIST_KEY]["API_BASE_URL"]
      assert_equal LOCALHOST_ONLY_ATS, written["NSAppTransportSecurity"]

      run_script(plist, configuration: "Debug", env: { "CR_APP_CFG_API_BASE_URL" => "http://192.168.1.20:3002" })
      assert_equal %w[192.168.1.20 localhost],
                   read_plist(plist).dig("NSAppTransportSecurity", "NSExceptionDomains").keys.sort
    end
  end
end
